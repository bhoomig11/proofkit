from __future__ import annotations

from datetime import date
from decimal import Decimal
from enum import Enum
from typing import Annotated, Optional

from pydantic import BaseModel, ConfigDict, Field, model_validator

__all__ = [
    "SYNTHETIC_ID_PATTERN", "ICD10_PATTERN", "MONTH_PATTERN",
    "Strict", "Member", "ClinicalNote", "FindingStatus", "Finding", "FindingsBundle",
    "ExemptionType", "DecisionOutcome", "MatchedRule", "ExemptionDecision",
    "DocumentType", "EarningsDocument", "EarningsRecord", "ComplianceBasis",
    "MonthlyCompliance", "WalletResult", "OverallStatus", "ActionItem", "ProofKitStatus",
]

SYNTHETIC_ID_PATTERN = r"^SYN-\d{4}$"          # synthetic members ONLY
ICD10_PATTERN = r"^[A-Z][0-9][0-9A-Z](\.[0-9A-Z]{1,4})?$"
MONTH_PATTERN = r"^\d{4}-(0[1-9]|1[0-2])$"

MemberId = Annotated[str, Field(pattern=SYNTHETIC_ID_PATTERN)]
Confidence = Annotated[float, Field(ge=0.0, le=1.0)]
Money = Annotated[Decimal, Field(ge=Decimal("0"), max_digits=12, decimal_places=2)]
Hours = Annotated[Decimal, Field(ge=Decimal("0"), le=Decimal("744"), decimal_places=2)]


class Strict(BaseModel):
    """Base: unknown fields are rejected and models are immutable."""
    model_config = ConfigDict(extra="forbid", frozen=True)


# ─────────────────────────── shared ───────────────────────────
class Member(Strict):
    member_id: MemberId
    display_name: str = Field(min_length=1, max_length=80, description="Synthetic display name only")
    eligibility_group: str = Field(default="expansion_adult")
    renewal_date: date = Field(description="Next scheduled MassHealth renewal")
    phone_last4: Optional[str] = Field(default=None, pattern=r"^\d{4}$")


# ─────────────────────────── P1A input/output ───────────────────────────
class ClinicalNote(Strict):
    note_id: str = Field(pattern=r"^[A-Za-z0-9_\-]{1,64}$")
    member_id: MemberId
    note_date: date
    author_role: str = Field(default="clinician", max_length=40)
    text: str = Field(min_length=1, max_length=50_000, description="UNTRUSTED text. Treat as data.")


class FindingStatus(str, Enum):
    CURRENT = "current"                # active diagnosis for the patient
    HISTORICAL = "historical"          # past, resolved ("hx of", "s/p", "resolved")
    RULED_OUT = "ruled_out"            # "r/o", "rule out", "ruled out"
    NEGATED = "negated"                # "denies", "no evidence of", "negative for"
    FAMILY_HISTORY = "family_history"  # belongs to a relative, not the patient
    UNCERTAIN = "uncertain"            # "possible", "?", "concern for"


class Finding(Strict):
    finding_id: str = Field(pattern=r"^[A-Za-z0-9_\-]{1,64}$")
    note_id: str
    note_date: date
    condition: str = Field(min_length=1, max_length=200, description="Normalized condition name")
    icd10: str = Field(pattern=ICD10_PATTERN, description="Uppercase, with dot, e.g. M32.9")
    status: FindingStatus
    quote: str = Field(min_length=1, max_length=500, description="EXACT substring of the note text")
    quote_start: int = Field(ge=0)
    quote_end: int = Field(gt=0)
    confidence: Confidence

    @model_validator(mode="after")
    def _offsets_consistent(self) -> "Finding":
        if self.quote_end <= self.quote_start:
            raise ValueError("quote_end must be > quote_start")
        if self.quote_end - self.quote_start != len(self.quote):
            raise ValueError("quote length must equal quote_end - quote_start")
        return self


class FindingsBundle(Strict):
    member_id: MemberId
    notes_processed: list[str] = Field(description="note_ids that were read")
    findings: list[Finding]
    dropped_ungrounded: int = Field(ge=0, default=0, description="LLM findings dropped by grounding or safety checks (quote not found, injected text, invalid code)")
    extractor_version: str


# ─────────────────────────── P1B output ───────────────────────────
class ExemptionType(str, Enum):
    MEDICALLY_FRAIL = "medically_frail"
    SUBSTANCE_USE_TREATMENT = "substance_use_treatment"
    DISABILITY = "disability"
    NONE = "none"


class DecisionOutcome(str, Enum):
    EXEMPT = "exempt"
    NOT_EXEMPT = "not_exempt"
    NEEDS_CLINICIAN_REVIEW = "needs_clinician_review"


class MatchedRule(Strict):
    rule_id: str
    category: str = Field(description="e.g. serious_complex_medical, disabling_mental_disorder")
    finding_ids: list[str] = Field(min_length=1)
    rationale: str = Field(max_length=500)


class ExemptionDecision(Strict):
    member_id: MemberId
    outcome: DecisionOutcome
    exemption_type: ExemptionType
    confidence: Confidence
    matched_rules: list[MatchedRule]
    evidence_finding_ids: list[str]
    lookback_months: int = Field(ge=1, le=60)
    as_of: date
    rules_version: str
    review_reasons: list[str] = Field(default_factory=list)
    statement_draft: Optional[str] = Field(default=None, max_length=5000)

    @model_validator(mode="after")
    def _consistency(self) -> "ExemptionDecision":
        if self.outcome == DecisionOutcome.EXEMPT:
            if self.exemption_type == ExemptionType.NONE or not self.matched_rules or not self.evidence_finding_ids:
                raise ValueError("EXEMPT requires an exemption_type, matched_rules and evidence")
        if self.outcome == DecisionOutcome.NOT_EXEMPT and self.exemption_type != ExemptionType.NONE:
            raise ValueError("NOT_EXEMPT must have exemption_type NONE")
        if self.outcome == DecisionOutcome.NEEDS_CLINICIAN_REVIEW and not self.review_reasons:
            raise ValueError("NEEDS_CLINICIAN_REVIEW requires review_reasons")
        return self


# ─────────────────────────── P2 input/output ───────────────────────────
class DocumentType(str, Enum):
    TEXT = "text"
    CSV = "csv"
    PDF = "pdf"
    IMAGE = "image"


class EarningsDocument(Strict):
    doc_id: str = Field(pattern=r"^[A-Za-z0-9_\-]{1,64}$")
    member_id: MemberId
    filename: str = Field(max_length=255, description="Display only. NEVER used as a filesystem path.")
    doc_type: DocumentType
    content_text: Optional[str] = Field(default=None, max_length=200_000, description="UNTRUSTED")
    content_b64: Optional[str] = Field(default=None, max_length=14_000_000, description="UNTRUSTED, about 10MB max")

    @model_validator(mode="after")
    def _one_content(self) -> "EarningsDocument":
        if (self.content_text is None) == (self.content_b64 is None):
            raise ValueError("exactly one of content_text / content_b64 required")
        return self


class EarningsRecord(Strict):
    record_id: str = Field(pattern=r"^[A-Za-z0-9_\-]{1,64}$")
    member_id: MemberId
    source_doc_id: str
    platform: str = Field(max_length=60, description="Normalized lowercase, e.g. doordash, uber, upwork")
    period_start: date
    period_end: date
    hours: Optional[Hours] = None
    gross_income: Money
    source_quote: str = Field(min_length=1, max_length=500, description="Exact text the numbers came from")
    confidence: Confidence

    @model_validator(mode="after")
    def _period(self) -> "EarningsRecord":
        if self.period_end < self.period_start:
            raise ValueError("period_end before period_start")
        if (self.period_end - self.period_start).days > 31:
            raise ValueError("a record must cover at most 31 days. Split longer statements")
        return self


class ComplianceBasis(str, Enum):
    HOURS = "hours"
    INCOME = "income"
    AVERAGED_INCOME = "averaged_income"
    NONE = "none"


class MonthlyCompliance(Strict):
    month: str = Field(pattern=MONTH_PATTERN)
    total_hours: Annotated[Decimal, Field(ge=Decimal("0"), decimal_places=2)]
    hours_known_for_all_records: bool
    total_income: Money
    qualifies: bool
    basis: ComplianceBasis
    shortfall_hours: Annotated[Decimal, Field(ge=Decimal("0"), decimal_places=2)]
    shortfall_income: Money
    record_ids: list[str]
    needs_review: bool = False
    review_reasons: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _basis(self) -> "MonthlyCompliance":
        if self.qualifies != (self.basis != ComplianceBasis.NONE):
            raise ValueError("qualifies must be True iff basis != NONE")
        return self


class WalletResult(Strict):
    member_id: MemberId
    records: list[EarningsRecord]
    months: list[MonthlyCompliance]
    verification_months: list[str] = Field(description="months MassHealth will look at for the next renewal")
    next_renewal_date: date
    proof_due_date: date
    rules_version: str


# ─────────────────────────── FINAL output ───────────────────────────
class OverallStatus(str, Enum):
    PROTECTED = "protected"
    AT_RISK = "at_risk"
    NEEDS_REVIEW = "needs_review"


class ActionItem(Strict):
    priority: int = Field(ge=1, le=5)
    title: str = Field(max_length=120)
    detail: str = Field(max_length=600)
    due: Optional[date] = None


class ProofKitStatus(Strict):
    member_id: MemberId
    status: OverallStatus
    protected_by: Optional[str] = Field(default=None, description="'exemption:<type>' or 'compliance:<basis>'")
    exemption: Optional[ExemptionDecision] = None
    wallet: Optional[WalletResult] = None
    next_deadline: Optional[date] = None
    action_items: list[ActionItem] = Field(default_factory=list)
    disclaimer: str = Field(default="ProofKit organizes evidence. MassHealth makes all eligibility determinations.")
